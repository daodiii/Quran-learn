// Builds quiz-data.js for the quiz mockups from the real Level 5 quiz page and the lesson titles.
// Run from the repo root: node docs/redesign/mockups/quiz/build-data.mjs
import fs from 'node:fs';
import path from 'node:path';

const page = fs.readFileSync('src/pages/learn/level-5/quiz.astro', 'utf8');
const m = page.match(/const questions = (\[[\s\S]*?\r?\n\]);\r?\n---/);
if (!m) throw new Error('questions array not found');
const all = new Function(`return ${m[1]}`)();

// Lesson titles by "level.order", read from the frontmatter.
const titles = {};
for (const lv of [1, 2, 3, 4, 5]) {
  const dir = `src/content/lessons/level-${lv}`;
  for (const f of fs.readdirSync(dir)) {
    const t = fs.readFileSync(path.join(dir, f), 'utf8');
    const title = t.match(/^title:\s*"?(.*?)"?\s*$/m)?.[1];
    const order = Number(t.match(/^order:\s*(\d+)/m)?.[1]);
    titles[`L${lv}.${String(order).padStart(2, '0')}`] = { title, id: `level-${lv}/${f.replace(/\.mdx?$/, '')}` };
  }
}
// A demo set of 6 real questions (ids from the page).
const pick = [1, 4, 6, 8, 10, 13].map((id) => all.find((q) => q.id === id)).filter(Boolean);
fs.writeFileSync(
  'docs/redesign/mockups/quiz/quiz-data.js',
  `// Generated by build-data.mjs from the real Level 5 quiz. Do not edit.\nwindow.QUIZ = ${JSON.stringify({ title: 'Level 5 Quiz', passingScore: 70, questions: pick, lessons: titles }, null, 1)};\n`
);
console.log(pick.map((q) => `${q.id}: ${q.question.slice(0, 70)}`).join('\n'));
