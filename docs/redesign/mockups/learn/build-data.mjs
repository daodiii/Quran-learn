// Builds learn-data.js for the Learn mockups from the real lessons and curriculum map.
//   node docs/redesign/mockups/learn/build-data.mjs
// Node 24 strips the types in curriculum-map.ts and reading-track.ts on import.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..', '..');
const { CURRICULUM_MAP } = await import(pathToFileURL(join(root, 'src/data/curriculum-map.ts')).href);
const { READING_TRACK } = await import(pathToFileURL(join(root, 'src/data/reading-track.ts')).href);

function front(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const out = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) continue;
    out[kv[1]] = kv[2].replace(/^"(.*)"$/, '$1').replace(/^'(.*)'$/, '$1');
  }
  return out;
}

const lessons = {};
for (let level = 1; level <= 5; level++) {
  const dir = join(root, 'src/content/lessons', `level-${level}`);
  for (const f of readdirSync(dir).filter(n => n.endsWith('.mdx'))) {
    const fm = front(readFileSync(join(dir, f), 'utf8'));
    lessons[`${level}:${+fm.order}`] = {
      id: `level-${level}/${f.replace(/\.mdx$/, '')}`,
      order: +fm.order,
      title: fm.title,
      kicker: fm.kicker || '',
      ar: fm.titleArabic || '',
      desc: fm.description || '',
    };
  }
}

const levelInfo = {
  1: { title: 'Foundation', ar: 'الأساسيات', blurb: 'Letters, vowels, word types and the first sentences.', needs: 'Starts from zero. No Arabic needed.' },
  2: { title: 'Core Grammar', ar: 'القواعد الأساسية', blurb: 'The three cases, possession and how a sentence is built.', needs: 'Needs Level 1: reading the script and the three word types.' },
  3: { title: 'Intermediate', ar: 'القواعد المتوسطة', blurb: 'Verbs, roots, all ten forms and the pronouns.', needs: 'Needs Level 2: the three cases and both sentence types.' },
  4: { title: 'Advanced', ar: 'القواعد المتقدمة', blurb: 'Conditionals, exceptions, weak verbs and rhetoric.', needs: 'Needs Level 3: verb forms and conjugation.' },
  5: { title: 'Applied Study', ar: 'التطبيق القرآني', blurb: 'Read whole passages with everything you have learned.', needs: 'Needs Level 4: all the grammar before it.' },
};

const surahNames = {};
const surahDir = join(root, 'src/content/surahs');
for (const f of readdirSync(surahDir)) {
  if (!f.endsWith('.mdx')) continue;
  const fm = front(readFileSync(join(surahDir, f), 'utf8'));
  surahNames[f.replace(/\.mdx$/, '')] = fm.name;
}

const levels = CURRICULUM_MAP.map(({ level, clusters }) => ({
  n: level,
  ...levelInfo[level],
  reviewHref: level >= 2 ? `/learn/level-${level}/review/` : null,
  vocabHref: `/learn/level-${level}/vocabulary/`,
  reading: READING_TRACK.filter(e => e.afterLevel === level).map(e => ({ slug: e.slug, name: surahNames[e.slug] || e.slug })),
  clusters: clusters.map(c => ({
    title: c.title,
    note: c.note || '',
    essential: !!c.essential,
    checkpoint: !!c.checkpoint,
    lessons: c.lessons.map(o => {
      const l = lessons[`${level}:${o}`];
      if (!l) throw new Error(`no lesson for level ${level} order ${o}`);
      return l;
    }),
  })),
}));

const total = levels.flatMap(l => l.clusters.flatMap(c => c.lessons)).length;
const groups = levels.flatMap(l => l.clusters).length;
writeFileSync(join(here, 'learn-data.js'), `// Generated by build-data.mjs. Do not edit.\nwindow.LEARN = ${JSON.stringify({ total, groups, levels }, null, 1)};\n`);
console.log(`${total} lessons, ${groups} topic groups, ${levels.length} levels`);
