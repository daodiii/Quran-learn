/** Surah names written plainly in a reference column, such as the first cell of «البقرة 2:102». */
const SURAH_NAMES = [
  'البقرة',
  'الحجر',
  'الرحمن',
  'الشيطان',
  'غافر',
];

/** Forms quoted from al-Jadwal: the original form of a word, or a pattern name. */
const BOOK_QUOTES = [
  'أسلم',
  'إِثنا',
  'ازديدوا',
  'استفل',
  'افتعل',
  'افتعوا',
  'عَلامتانِ',
  'مرضوي',
  'يستخفيون',
  'يمشيون',
];

export const UNVOWELLED_OK: ReadonlySet<string> = new Set([...IRAB_TERMS, ...SURAH_NAMES, ...BOOK_QUOTES]);

/** True when the token (ignoring Arabic commas and semicolons) is on the list. */
export function isUnvowelledOk(token: string): boolean {
  return UNVOWELLED_OK.has(token.replace(/[،؛؟]/g, ''));
}
