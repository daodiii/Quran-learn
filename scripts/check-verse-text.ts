/**
 * Compare the Arabic in lesson <ArabicExample> blocks with the verse text in the
 * Quranic Arabic Corpus file (Tanzil Uthmani text, as segmented by the Corpus).
 * Comparison is on letters only: diacritics, Quranic marks and spaces are ignored,
 * hamza-carrier variants are folded, and every alef and yaa is dropped, so
 * spelling-convention differences (full alif vs dagger alif) do not count. A lesson example passes if its letters appear inside the verse range.
 *
 *   npx tsx scripts/check-verse-text.ts
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { bwToArabic } from './lib/buckwalter';

const fold = (s: string) =>
  s
    .normalize('NFC')
    .replace(/[ؐ-ًؚ-ٰٟۖ-ۭـ‌‍࣓-ࣿ]/g, '')
    .replace(/[أإآٱٲٳ]/g, 'ا')
    .replace(/[ىئي]/g, 'ي')
    .replace(/[ؤ]/g, 'و')
    .replace(/[ءہ]/g, '')
    .replace(/ة/g, 'ه')
    .replace(/[اي]/g, '') // Uthmani and standard spelling differ on long a and on yaa/alif maqsura, so both are dropped
    .replace(/[^ء-ي]/g, '');

// verse -> folded letters
const verseWords = new Map<string, Map<number, string>>();
for (const line of readFileSync('src/data/morphology/quranic-corpus-morphology-0.4.txt', 'utf8').split(/\r?\n/)) {
  const m = line.match(/^\((\d+):(\d+):(\d+):(\d+)\)\t([^\t]*)\t/);
  if (!m) continue;
  const v = `${m[1]}:${m[2]}`;
  const w = verseWords.get(v) ?? new Map<number, string>();
  w.set(+m[3], (w.get(+m[3]) ?? '') + bwToArabic(m[5]));
  verseWords.set(v, w);
}
const verseText = (v: string) => {
  const w = verseWords.get(v);
  return w ? fold([...w.entries()].sort((a, b) => a[0] - b[0]).map(([, t]) => t).join('')) : null;
};

type Result = { id: string; ref: string; arabic: string; status: 'ok' | 'mismatch' | 'no-ref' | 'bad-ref' };
const results: Result[] = [];
const dir = 'src/content/lessons';
for (const lvl of readdirSync(dir).filter((d) => d.startsWith('level-'))) {
  for (const f of readdirSync(join(dir, lvl)).filter((f) => f.endsWith('.mdx') && !f.startsWith('_'))) {
    const txt = readFileSync(join(dir, lvl, f), 'utf8');
    for (const block of txt.match(/<ArabicExample[\s\S]*?\/>/g) ?? []) {
      const ar = block.match(/\barabic=(?:"([^"]*)"|\{`([^`]*)`\}|\{'([^']*)'\})/);
      const rf = block.match(/reference="([^"]*)"/);
      const id = `${lvl}/${f.replace('.mdx', '')}`;
      if (!ar) continue;
      const arabic = ar[1] ?? ar[2] ?? ar[3];
      if (!rf) { results.push({ id, ref: '', arabic, status: 'no-ref' }); continue; }
      const rm = rf[1].match(/(\d+):(\d+)(?:\s*[-–]\s*(\d+))?\s*$/);
      if (!rm) { results.push({ id, ref: rf[1], arabic, status: 'bad-ref' }); continue; }
      const [s, a, b] = [rm[1], +rm[2], rm[3] ? +rm[3] : +rm[2]];
      let hay = '';
      let missing = false;
      for (let v = a; v <= b; v++) {
        const t = verseText(`${s}:${v}`);
        if (t === null) { missing = true; break; }
        hay += t;
      }
      if (missing) { results.push({ id, ref: rf[1], arabic, status: 'bad-ref' }); continue; }
      // An example may hold several fragments joined by "..." or a dash; every fragment must appear.
      const frags = arabic.split(/\s*(?:\.\.\.|…|—|–|\|)\s*/).map(fold).filter(Boolean);
      const ok = frags.length > 0 && frags.every((fr) => hay.includes(fr));
      results.push({ id, ref: rf[1], arabic, status: ok ? 'ok' : 'mismatch' });
    }
  }
}
const count = (s: Result['status']) => results.filter((r) => r.status === s).length;
const bad = results.filter((r) => r.status === 'mismatch');
let md = `# Lesson verse text check\n\nGenerated by \`scripts/check-verse-text.ts\`. Compares letters only (diacritics, marks, alef/yaa/hamza-carrier variants ignored, every alef and yaa dropped) against the verse text in the Corpus file (Tanzil Uthmani).\n\n`;
md += `- Examples checked: ${results.length}\n- Letters match the cited verse: ${count('ok')}\n- Letters do **not** match: ${count('mismatch')}\n- Reference not parseable or verse missing: ${count('bad-ref')}\n- No reference: ${count('no-ref')}\n\n`;
md += `A mismatch is not always an error: the example may be a constructed phrase (not a verse), a paraphrase, or use a different spelling convention. Each needs a person's look.\n\n## Mismatches\n\n| Lesson | Reference | Arabic in the lesson |\n|---|---|---|\n`;
for (const r of bad) md += `| ${r.id} | ${r.ref} | ${r.arabic} |\n`;
writeFileSync('docs/curriculum/verse-text-check.md', md);
console.log({ total: results.length, ok: count('ok'), mismatch: count('mismatch'), badRef: count('bad-ref'), noRef: count('no-ref') });
