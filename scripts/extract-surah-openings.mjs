// scripts/extract-surah-openings.mjs
// One-off: harvests the byte-exact opening lines + revelation place from the
// verified v3 mockup into src/data/surah-openings.ts. Rerun only if the
// mockup data ever changes.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('.planning/redesign-v3-sections/surahs-4-astrolabe-royale.html', 'utf8');
const rows = [...src.matchAll(/\{num:(\d+),ar:"[^"]*",name:"[^"]*",v:\d+,rev:"(Meccan|Medinan)",diff:"[^"]*",open:"([^"]*)"\}/g)];
if (rows.length !== 38) throw new Error(`expected 38 surah rows in mockup, got ${rows.length}`);

const entries = rows.map(([, num, rev, open]) =>
  `  ${num}: { open: ${JSON.stringify(open)}, rev: '${rev}' },`).join('\n');

writeFileSync('src/data/surah-openings.ts', `// GENERATED by scripts/extract-surah-openings.mjs — do not hand-edit.
// Opening lines (byte-exact from the surah corpus, harvested via the verified
// 2026-07-10 v3 mockup) + revelation place for the /surahs astrolabe plate.
// Never retype or normalize the Arabic strings.
export interface SurahOpening { open: string; rev: 'Meccan' | 'Medinan' }

export const SURAH_OPENINGS: Record<number, SurahOpening> = {
${entries}
};
`);
console.log('wrote src/data/surah-openings.ts with', rows.length, 'entries');
