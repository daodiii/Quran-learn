/**
 * Draft Vocabulary-course outline from docs/curriculum/frequency.json.
 * Function words (particles, pronouns, relatives...) are grouped by class.
 * Content words (nouns, verbs, adjectives, proper nouns) go in lessons of 12 by frequency.
 *
 *   npx tsx scripts/analyze-corpus-frequency.ts && npx tsx scripts/build-vocab-outline.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

type Row = { rank: number; lemmaBw: string; arabic: string; pos: string; root: string | null; count: number };
import { bwToArabic } from './lib/buckwalter';

// bwLemmaToArabic renders the lemma {ll~ah with a stray sukun, so it is written out here.
const arabicOf = (r: { lemmaBw: string; arabic: string }) =>
  r.lemmaBw === '{ll~ah' ? 'ٱللَّه' : r.lemmaBw.startsWith('~') ? bwToArabic(r.lemmaBw.split(':').slice(1).join(':')) : r.arabic;

const data = JSON.parse(readFileSync('docs/curriculum/frequency.json', 'utf8'));
const TOTAL: number = data.totalWords;
const top: Row[] = data.top500;

const CONTENT = new Set(['N', 'V', 'ADJ', 'PN']);
const CLASS_NAMES: Record<string, string> = {
  P: 'Prepositions',
  PRON: 'Pronouns',
  REL: 'Relative words (who, which, what)',
  DEM: 'This and that',
  NEG: 'Negation',
  COND: 'If',
  ACC: 'Inna and its sisters',
  SUB: 'Joining words (that, so that)',
  RES: 'Except / only',
  CONJ: 'And, but, so, then',
  T: 'Time words (when, then)',
  LOC: 'Place words (there, where)',
  INTG: 'Question words',
  CERT: 'Certainty (qad)',
  EMPH: 'Emphasis (la-)',
  VOC: 'Calling (ya)',
  RET: 'Turning away (bal)',
  AMD: 'But (lakin)',
  EXL: 'Explanation',
  EXP: 'Exceptive',
  SUP: 'Supplemental',
  PRP: 'Purpose',
  RSLT: 'Result',
  PRO: 'Prohibition',
  CIRC: 'Circumstantial',
  INC: 'Inceptive',
  CAUS: 'Cause',
  FUT: 'Future (sa-)',
};
const plural = (n: number, w: string) => `${n} ${w}${n === 1 ? '' : 's'}`;
const pct = (n: number) => ((n / TOTAL) * 100).toFixed(1);

// Pronouns are left out: the corpus splits them into many spelling variants, and they are taught in L3.08-09.
const fn = top.filter((r) => !CONTENT.has(r.pos) && r.pos !== 'PRON');
const content = top.filter((r) => CONTENT.has(r.pos));
const fnTotal = fn.reduce((s, r) => s + r.count, 0);

let md = `# Vocabulary course: draft outline

Generated by \`scripts/build-vocab-outline.ts\` from \`docs/curriculum/frequency.json\` (Quranic Arabic Corpus v0.4, ${TOTAL.toLocaleString('en')} words).
Words are counted by lemma: a word's prefixes (wa-, fa-, bi-, al-) are removed, and attached pronouns are not counted as separate words.
This is a draft order, not final lessons. Glosses, example verses and the choice of lemmas still need a person to check.

## Shape

- **Unit 0, little words:** ${fn.length} function-word lemmas from the top 500 (pronouns not included; they belong to grammar lessons L3.08-09), together ${pct(fnTotal)}% of all words in the Quran. Taught next to the grammar lessons that need them.
- **Units 1+, content words:** ${content.length} nouns, verbs, adjectives and names from the top 500, 12 per lesson (${Math.ceil(content.length / 12)} lessons), in order of frequency.
- Cumulative coverage below counts Unit 0 plus the content lessons so far.

## Unit 0: little words

`;
const byClass = new Map<string, Row[]>();
for (const r of fn) (byClass.get(r.pos) ?? byClass.set(r.pos, []).get(r.pos)!).push(r);
for (const [pos, rows] of [...byClass.entries()].sort((a, b) => b[1].reduce((s, r) => s + r.count, 0) - a[1].reduce((s, r) => s + r.count, 0))) {
  const sum = rows.reduce((s, r) => s + r.count, 0);
  md += `### ${CLASS_NAMES[pos] ?? pos} (${plural(rows.length, "word")}, ${pct(sum)}% of all words)\n\n`;
  md += rows.map((r) => `${arabicOf(r)} (${r.count.toLocaleString('en')})`).join(' · ') + '\n\n';
}

md += `## Units 1+: content words, 12 per lesson\n\n| Lesson | Words (count in the Quran) | Cumulative coverage |\n|---|---|---|\n`;
let running = fnTotal;
for (let i = 0; i < content.length; i += 12) {
  const chunk = content.slice(i, i + 12);
  running += chunk.reduce((s, r) => s + r.count, 0);
  md += `| V${String(i / 12 + 1).padStart(2, '0')} | ${chunk.map((r) => `${arabicOf(r)} ${r.pos === 'V' ? '(v)' : r.pos === 'PN' ? '(name)' : ''} ${r.count}`.replace(/\s+/g, ' ')).join(' · ')} | ${pct(running)}% |\n`;
}
writeFileSync('docs/curriculum/vocabulary-outline.md', md);
console.log(`function lemmas ${fn.length} (${pct(fnTotal)}%), content lemmas ${content.length}, lessons ${Math.ceil(content.length / 12)}, final coverage ${pct(running)}%`);
